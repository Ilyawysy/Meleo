def build_question_user_message(
    topic_label: str,
    subtopic_label: str,
    app_context: str,
) -> str:
    return f"ТЕМА: {topic_label}\nПОДТЕМА: {subtopic_label}\n\n{app_context}"


def build_card_user_message(
    topic_label: str,
    subtopic_label: str,
    question: str,
    answer: str,
    app_context: str,
    prev_card: dict | None,
    feedback: str | None,
) -> str:
    parts = [
        f"ТЕМА: {topic_label}",
        f"ПОДТЕМА: {subtopic_label}",
        f"ВОПРОС: {question}",
        f"ОТВЕТ ПОЛЬЗОВАТЕЛЯ: {answer}",
        "",
        app_context,
    ]
    if prev_card is not None:
        parts.append("")
        parts.append("[ПРЕДЫДУЩАЯ КАРТОЧКА]")
        messages = prev_card.get("messages", [])
        if messages:
            parts.append("Тексты: " + " | ".join(messages))
        action_label = prev_card.get("action_label", "")
        if action_label:
            parts.append(f"Действие: {action_label}")
    if feedback is not None:
        parts.append("")
        parts.append(f"[ФИДБЭК ПОЛЬЗОВАТЕЛЯ]: {feedback}")
    return "\n".join(parts)
